#!/bin/bash
# wasp-build.sh — run a PRODUCTION `wasp build` without breaking local state.
#
# A bare `wasp build` in this repo always fails:
#
#   app.emailSender must not be set to Dummy when building for production.
#
# That is deliberate. main.wasp.ts carries provider: "Dummy" so local `wasp
# start` prints confirmation links to the server log instead of sending mail;
# the deploy path flips it to SMTP for the build and flips it back. The trap is
# what happens next — `wasp build` clears .wasp/out BEFORE it fails, so the
# generated SDK goes with it and `deploy-dev.sh` can no longer build the
# frontend until `wasp start` regenerates it.
#
# Use this when you want to answer "does this compile for production?" without
# deploying. deploy-server.sh does the same flip as part of a real deploy; this
# is the read-only half of it.
#
#   ./wasp-build.sh
set -e
cd "$(dirname "$0")"

if ! git diff --quiet -- main.wasp.ts; then
  echo "❌ main.wasp.ts has uncommitted changes."
  echo "   This script rewrites it in place and restores it with 'git checkout',"
  echo "   which would discard your edits. Commit or stash them first."
  exit 1
fi

echo "📧 Switching emailSender Dummy → SMTP for the build..."
# Restore main.wasp.ts however this exits — success, failure, or Ctrl-C.
trap 'echo "↩️  Reverting main.wasp.ts emailSender → Dummy"; git checkout -- main.wasp.ts 2>/dev/null || true' EXIT
sed -i '' 's/provider: "Dummy",/provider: "SMTP",/' main.wasp.ts

echo "🔨 wasp build..."
wasp build

echo ""
echo "✅ Production build succeeded."
echo "   Note: .wasp/out has been regenerated by this build. \`wasp start\` will"
echo "   put it back into dev shape the next time you run it."
