import { describe, expect, it } from "vitest";
import {
  V4_META,
  V4_ONLY_PROGRAMS,
  V4_PANEL_A_BASIS,
  V4_PANEL_C,
  v4PanelABasisByCode,
} from "../v4/data/v4PanelC";
import { v3ProgramByCode } from "../v3/data/v3Programs";
import { basisMedian, isOwnRecord } from "../v4/exposureBasis";
import { v4Quadrant } from "../v4/v4Position";

const TIERS = [
  "exact",
  "variant",
  "pooled",
  "combined",
  "cognate",
  "partial",
  "field",
] as const;

/**
 * Every program scored on v4 carries an exposure value on a STATED basis
 * (docs/dfva-v4-panela-basis.md). These guard the contract the report page
 * relies on: no scored coursework program without a value, no value without
 * a basis, and field-tier values placed against the field-basis median only.
 * `V4_PANEL_A_BASIS` is generated by `npm --prefix scripts run dfva:gen-v4`.
 */
describe("V4 Panel A basis contract", () => {
  const scored = Object.keys(V4_PANEL_C);

  it("every scored program has a basis with a valid tier and ≥1 source", () => {
    for (const code of scored) {
      const b = V4_PANEL_A_BASIS[code];
      expect(b, code).toBeDefined();
      expect(TIERS).toContain(b.tier);
      expect(b.sources.length, code).toBeGreaterThan(0);
      expect(b.indexVariant).toBe("AIOE-2021");
      expect(v4PanelABasisByCode(code.toUpperCase())).toBe(b);
    }
  });

  it("every v4-only program has a non-null exposure that matches its basis", () => {
    for (const [code, p] of Object.entries(V4_ONLY_PROGRAMS)) {
      expect(p.exposure, code).not.toBeNull();
      expect(p.exposureBasis, code).not.toBeNull();
      expect(p.exposureBasis?.tier).toBe(V4_PANEL_A_BASIS[code].tier);
      expect(p.exposure as number).toBeGreaterThan(0);
      expect(p.exposure as number).toBeLessThanOrEqual(100);
    }
  });

  it("grain follows tier", () => {
    for (const b of Object.values(V4_PANEL_A_BASIS)) {
      if (b.tier === "exact" || b.tier === "variant")
        expect(b.grain).toBe("program");
      if (b.tier === "pooled" || b.tier === "combined")
        expect(b.grain).toBe("program-family");
      if (b.tier === "cognate" || b.tier === "partial")
        expect(b.grain).toBe("related-program");
      if (b.tier === "field") {
        expect(b.grain).toBe("field");
        expect(b.field).toBeTruthy();
      }
    }
  });

  it("reference-cohort programs keep their v3 value and carry a basis label", () => {
    // The resolver reproduces the reconciliation package; the label is the
    // only thing v4 adds for these programs.
    for (const code of scored) {
      const v3 = v3ProgramByCode(code);
      if (!v3) continue;
      expect(V4_PANEL_A_BASIS[code]).toBeDefined();
      expect(V4_ONLY_PROGRAMS[code]).toBeUndefined();
    }
  });

  it("field-tier programs are placed against the field-basis median, others against the alumni-title median", () => {
    for (const [code, b] of Object.entries(V4_PANEL_A_BASIS)) {
      const median = basisMedian(b);
      if (b.tier === "field") {
        expect(median).toBe(V4_META.expMedianField);
        if (V4_META.expMedianField !== null) {
          // A field-basis median exists → a label can be assigned.
          const exp = V4_ONLY_PROGRAMS[code]?.exposure ?? null;
          if (exp !== null)
            expect(v4Quadrant(exp, V4_PANEL_C[code].adaptiveness, b)).not.toBeNull();
        } else {
          expect(v4Quadrant(80, 9, b)).toBeNull();
        }
      } else {
        expect(median).toBe(V4_META.expMedian);
      }
    }
  });

  it("the two medians are on different bases and the field one, when published, is lower", () => {
    // Reconciliation history: field-grain values run ~10 points below
    // alumni-title values. A field median at or above 90.9 would mean the two
    // bases had been mixed.
    expect(V4_META.expMedian).toBe(90.9);
    if (V4_META.expMedianField !== null) {
      expect(V4_META.expMedianField).toBeLessThan(V4_META.expMedian);
      expect(V4_META.expMedianField).toBeGreaterThan(50);
    }
  });

  it("isOwnRecord is true only for exact/variant", () => {
    for (const b of Object.values(V4_PANEL_A_BASIS)) {
      expect(isOwnRecord(b)).toBe(b.tier === "exact" || b.tier === "variant");
    }
  });

  it("a share-weighted figure is only ever carried on the field tier", () => {
    for (const b of Object.values(V4_PANEL_A_BASIS)) {
      if (b.exposureWeighted !== undefined) expect(b.tier).toBe("field");
    }
  });
});
